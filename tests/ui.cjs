const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const { pathToFileURL } = require('node:url');
const path = require('node:path');
(async () => {
 const browser = await chromium.launch({headless:true});
 const page = await browser.newPage({viewport:{width:1366,height:900}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 try {
  await page.goto(pathToFileURL(path.resolve('index.html')).href);
  await page.locator('[data-menu="project"]').click();
  await page.locator('#projectSettings').click();
  await page.locator('#projectStart').fill('2027-01-04');
  await page.locator('#projectFinish').fill('2030-12-31');
  await page.locator('#projectForm button[type="submit"]').click();
  assert.match(await page.locator('#projectDates').innerText(),/2027-01-04/);
  await page.locator('[data-menu="task"]').click();
  await page.locator('#add').click();
  await page.locator('#taskName').fill('Disseny del projecte');
  await page.locator('#taskDuration').fill('5');
  await page.locator('#taskDuration').dispatchEvent('change');
  assert.equal(await page.locator('#taskFinish').inputValue(),'2027-01-08');
  await page.locator('#taskFinish').fill('2027-01-11');
  await page.locator('#taskFinish').dispatchEvent('change');
  assert.equal(await page.locator('#taskDuration').inputValue(),'6');
  await page.locator('#taskForm button[type="submit"]').click();
  assert.equal(await page.locator('#rows tr').count(),1);
  const fits=await page.locator('.chart').evaluate(el=>({width:el.clientWidth,scroll:el.scrollWidth}));
  assert.ok(fits.width>200,'Gantt visible beside table');
  assert.ok(fits.scroll<=fits.width+2,'fit has no horizontal overflow even for a four-year project');
  assert.ok(await page.evaluate(()=>rangeForChart().to>'2030-12-31'),'full project range is retained');
  await page.locator('.view-switch [data-view="grid"]').click();
  assert.ok(await page.locator('#rows [data-k="resource"]').isVisible());
  await page.locator('#rows [data-k="progress"]').fill('50');
  await page.locator('#rows [data-k="progress"]').dispatchEvent('change');
  await page.locator('.view-switch [data-view="board"]').click();
  assert.match(await page.locator('.board-column').nth(1).innerText(),/Disseny del projecte/);
  await page.locator('.task-card button').click();
  await page.locator('#taskDeps').fill('1FC');
  await page.locator('#taskDeps').dispatchEvent('change');
  await page.locator('#taskForm button[type="submit"]').click();
  assert.ok(await page.locator('#taskModal').evaluate(e=>e.classList.contains('open')),'invalid task stays open');
  await page.locator('#cancelTask').click();
  await page.locator('.view-switch [data-view="grid"]').click();
  assert.equal(await page.locator('#rows [data-k="deps"]').inputValue(),'');
  await page.locator('#search').fill('inexistent');
  assert.equal(await page.locator('#rows tr').count(),0);
  await page.locator('#search').fill('');
  await page.locator('[data-menu="view"]').click();
  await page.locator('#fit').click();
  await page.locator('[data-menu="project"]').click();
  await page.locator('#projectSettings').click();
  await page.locator('#projectFinish').fill('2027-01-05');
  await page.locator('#projectForm button[type="submit"]').click();
  assert.match(await page.locator('#deadlineStatus').innerText(),/Supera/);
  await page.reload();
  assert.equal(await page.locator('#rows [data-k="name"]').inputValue(),'Disseny del projecte');
  assert.match(await page.locator('#projectDates').innerText(),/2027-01-05/);
  for(const width of [1024,390]){
   await page.setViewportSize({width,height:850});
   await page.waitForTimeout(100);
   const layout=await page.evaluate(()=>({body:document.documentElement.scrollWidth,viewport:innerWidth,chart:document.querySelector('.chart').clientWidth,scroll:document.querySelector('.chart').scrollWidth}));
   assert.ok(layout.body<=layout.viewport+1,'no page-wide horizontal scroll at '+width);
   assert.ok(layout.scroll<=layout.chart+2,'fit works at '+width);
  }
  assert.deepEqual(errors,[]);
  console.log('UI passed: project dates, task finish, menus, grid, board, filtering, invalid input rollback, responsive Gantt and persistence');
 } finally {await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)});
